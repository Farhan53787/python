Oper = input("Operation you want to perform:")

if Oper == "addition":
    num1 = int(input("Enter the first number: "))
    num2 = int(input("Enter the second number: "))
    print(num1 + num2)

elif Oper == "subtraction":
    num1 = int(input("Enter the first number: "))
    num2 = int(input("Enter the second number: "))
    print(num1 - num2)

elif Oper == "multiplication":
    num1 = int(input("Enter the first number: "))
    num2 = int(input("Enter the second number: "))
    print(num1 * num2)

elif Oper == "division":
    num1 = int(input("Enter the first number: "))
    num2 = int(input("Enter the second number: "))
    print(num1 / num2)