fruits = ["mango", "lichi", "orange", "apple", "banana"]

print("I love " + (fruits[0]) + " the most.")

print(f"I love {len(fruits)} fruits the most.")

fruits.append("grapes")
print(fruits)

fruits.remove("apple")
print(fruits)

fruits.sort()
print(fruits)

fruits.reverse()
print(fruits)

fruits.insert(2, "kiwi")
print(fruits)

fruits.pop()
print(fruits)

fruits.clear()
print(fruits)